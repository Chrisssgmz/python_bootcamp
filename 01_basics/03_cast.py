# 03_cast.py
# casting is the process of converting a value from one data type to another.

print("Type casting:")

# int to float and float to int
print("int to float:", float(5))
print("float to int:", int(5.99))

# str to int and float
print("int to str:", str(5))
print("str to int:", int("5"))

# str to float:", float("5.99"))
print(bool(0))
print(bool(1))
print(bool("hello"))
print(bool(""))