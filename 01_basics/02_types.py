# int, float, complex, str, bool, NoneType, list, tuple, dict, range, set...

# int
print(type("int:"))
print(type(0))
print(type(-15))
print(type(50000))

# float
print(type("float:"))
print(type(3.14))
print(type(1.0))
print(type(1e3))

# complex
print(type("complex:"))
print(type(3+4j))
print(type(1+2j))
print(type(1e3+1e3j))

# str
print(type("str:"))
print(type("hello"))
print(type('world'))
print(type("""multi-line
string"""))

# bool
print(type("bool:"))
print(type(True))
print(type(False))

# NoneType
print(type("NoneType:"))
print(type(None))